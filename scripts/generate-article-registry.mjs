/**
 * Emits lib/generated/articleRegistry.ts by scanning content/options/.
 *
 * The registry maps (locale, optionKey) to a distinct static `import()` call.
 * Distinct calls matter: a template-literal dynamic import cannot be analysed
 * by the bundler, so the whole content tree would be pulled into one chunk.
 *
 * It is also the single source of truth for *which locales are translated*.
 * A locale missing an article falls back to English and the page then marks
 * itself noindex — see lib/optionArticle.ts. That is what lets translations
 * land one locale at a time without ever publishing near-duplicate pages.
 *
 * Chained into `build` ahead of `next build`, like gen:options, so adding a
 * content file needs no manual registry edit.
 */
import { writeFileSync, mkdirSync, readdirSync, existsSync } from 'node:fs';
import * as prettier from 'prettier';

const root = new URL('../', import.meta.url);
const contentDir = new URL('content/options/', root);
const out = new URL('lib/generated/articleRegistry.ts', root);

/** Locale codes are whatever common/messages/ defines — the existing source of truth. */
const knownLocales = new Set(
	readdirSync(new URL('common/messages/', root))
		.filter((f) => f.endsWith('.json'))
		.map((f) => f.replace(/\.json$/, '')),
);

const tree = new Map();

if (existsSync(contentDir)) {
	for (const locale of readdirSync(contentDir, { withFileTypes: true })) {
		if (!locale.isDirectory()) continue;
		if (!knownLocales.has(locale.name)) {
			throw new Error(
				`content/options/${locale.name}/ is not a known locale — expected one of ${[...knownLocales].sort().join(', ')}`,
			);
		}
		const keys = readdirSync(new URL(`${locale.name}/`, contentDir))
			.filter((f) => f.endsWith('.ts'))
			.map((f) => f.replace(/\.ts$/, ''))
			.sort();
		if (keys.length > 0) tree.set(locale.name, keys);
	}
}

const locales = [...tree.keys()].sort();

const body = locales
	.map((locale) => {
		const entries = tree
			.get(locale)
			.map(
				(key) => `\t\t${JSON.stringify(key)}: () => import('@/content/options/${locale}/${key}'),`,
			)
			.join('\n');
		return `\t${JSON.stringify(locale)}: {\n${entries}\n\t},`;
	})
	.join('\n');

const coverage = locales
	.map((locale) => `\t${JSON.stringify(locale)}: ${JSON.stringify(tree.get(locale))},`)
	.join('\n');

const source = `/* AUTO-GENERATED by scripts/generate-article-registry.mjs — do not edit by hand.
   Regenerate with \`bun run gen:articles\` (runs automatically as part of \`bun run build\`). */
import type { OptionArticle } from '@/common/interface/OptionArticle';

type ArticleModule = { default: OptionArticle };

/**
 * Which option keys each locale ships an original article for.
 *
 * Plain data with no imports, so app/sitemap.ts can ask "is this translated?"
 * 520 times without dragging a single article into its module graph.
 */
export const ARTICLE_COVERAGE: Readonly<Record<string, readonly string[]>> = {
${coverage}
};

/**
 * locale -> option key -> lazy import. Every specifier is a string literal:
 * this build runs on Turbopack, whose dynamic-request resolution is narrower
 * than webpack's, so a template-literal path built from two variables is not
 * worth the risk. Nothing here is evaluated until a page awaits it.
 */
export const ARTICLES: Record<string, Record<string, () => Promise<ArticleModule>>> = {
${body}
};
`;

const config = await prettier.resolveConfig(out.pathname);
const formatted = await prettier.format(source, { ...config, parser: 'typescript' });

mkdirSync(new URL('lib/generated/', root), { recursive: true });
writeFileSync(out, formatted);

const total = locales.reduce((n, l) => n + tree.get(l).length, 0);
console.warn(
	`generated article registry: ${total} articles across ${locales.length} locale(s) [${locales.join(', ') || 'none'}]`,
);
