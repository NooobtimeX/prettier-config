/**
 * Emits lib/generated/prettierOptions.ts from the pinned `prettier` package.
 *
 * Why this is allowed despite "never bundle Prettier" (CLAUDE.md):
 *  - it runs at BUILD time in Node, never in the browser or the server runtime;
 *  - it calls getSupportInfo() — metadata extraction, not formatting;
 *  - its output is plain data, so no `prettier` import survives into either
 *    bundle. Assert it: after a build, `.next/standalone/node_modules/prettier`
 *    must still not exist.
 *
 * The one formatting call below runs Prettier over this repo's own generated
 * source so it satisfies .prettierrc — which CLAUDE.md explicitly permits.
 *
 * Chained into `build`, so every deploy regenerates from whatever version
 * package.json pins. Bumping `prettier` is the entire maintenance action; no
 * hand-authored option copy to fall out of date.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import * as prettier from 'prettier';

const require = createRequire(import.meta.url);
const { version } = require('prettier/package.json');
const out = new URL('../lib/generated/prettierOptions.ts', import.meta.url);

const kebab = (key) => key.replace(/([A-Z])/g, '-$1').toLowerCase();

const { options } = await prettier.getSupportInfo();

const snapshot = options
	.map((opt) => ({
		key: opt.name,
		category: opt.category ?? 'Other',
		type: opt.type,
		description: opt.description ?? '',
		default: opt.default ?? null,
		choices: (opt.choices ?? []).map((c) => ({
			value: String(c.value),
			description: c.description ?? '',
		})),
		// Prettier's CLI negates booleans that default to true: `--no-semi`, not `--semi`.
		cliFlag:
			opt.type === 'boolean' && opt.default === true
				? `--no-${kebab(opt.name)}`
				: `--${kebab(opt.name)}`,
		...(opt.array ? { array: true } : {}),
		...(opt.range ? { range: opt.range } : {}),
	}))
	.sort((a, b) => a.category.localeCompare(b.category) || a.key.localeCompare(b.key));

const source = `/* AUTO-GENERATED by scripts/generate-prettier-options.mjs — do not edit by hand.
   Regenerate with \`bun run gen:options\` (runs automatically as part of \`bun run build\`). */
import type { StaticPrettierOption } from '@/common/interface/StaticPrettierOption';

/** The Prettier release this snapshot was generated from. Rendered on-page so staleness is visible. */
export const PRETTIER_SNAPSHOT_VERSION = '${version}';

export const STATIC_PRETTIER_OPTIONS: readonly StaticPrettierOption[] = ${JSON.stringify(snapshot, null, 2)};
`;

const config = await prettier.resolveConfig(out.pathname);
// parser passed explicitly rather than relying on filepath inference
const formatted = await prettier.format(source, { ...config, parser: 'typescript' });

mkdirSync(new URL('../lib/generated/', import.meta.url), { recursive: true });
writeFileSync(out, formatted);

console.warn(`generated ${snapshot.length} Prettier options from prettier@${version}`);
